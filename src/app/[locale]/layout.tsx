import type { Metadata } from "next";
import { notFound } from "next/navigation";
import { NextIntlClientProvider, hasLocale } from "next-intl";
import { getMessages, getTranslations, setRequestLocale } from "next-intl/server";
import { routing } from "@/i18n/routing";
import { clientMessages } from "@/i18n/client-messages";
import Tracking from "@/components/tracking/Tracking";
import RootDocument from "@/app/_components/RootDocument";

type Props = {
  children: React.ReactNode;
  params: Promise<{ locale: string }>;
};

const BASE_URL = "https://meapica.es";

const LOCALE_MAP: Record<string, string> = {
  es: "es_ES",
  ca: "ca_ES",
  en: "en_US",
  fr: "fr_FR",
};

export async function generateMetadata({ params }: Props): Promise<Metadata> {
  const { locale } = await params;
  const t = await getTranslations({ locale, namespace: "metadata" });

  const canonicalUrl = `${BASE_URL}/${locale}`;

  return {
    metadataBase: new URL(BASE_URL),
    title: {
      default: t("title"),
      template: `%s | Meapica`,
    },
    description: t("description"),
    keywords: t("keywords"),
    authors: [{ name: "Meapica" }],
    creator: "Meapica",
    publisher: "Meapica",
    icons: {
      shortcut: "/favicon.ico",
      icon: [
        { url: "/images/favicon-32.png", sizes: "32x32", type: "image/png" },
        { url: "/images/favicon-16.png", sizes: "16x16", type: "image/png" },
      ],
      apple: "/images/apple-touch-icon.png",
    },
    manifest: "/manifest.json",
    // No `alternates` here: a layout's canonical/hreflang is inherited by every page that
    // does not set its own, and by 404s (notFound() keeps the layout metadata), which then
    // pointed canonical at the home. Each indexable page sets its own (home: [locale]/page.tsx).
    openGraph: {
      title: t("title"),
      description: t("description"),
      type: "website",
      url: canonicalUrl,
      siteName: "Meapica",
      locale: LOCALE_MAP[locale] || "es_ES",
      // Images are auto-generated by opengraph-image.tsx in this route segment
    },
    twitter: {
      card: "summary_large_image",
      title: t("title"),
      description: t("description"),
      // Images are auto-generated by twitter-image.tsx in this route segment
    },
    // index/follow is the default, so no explicit "index, follow" robots tag: it
    // would sit next to the "noindex" Next injects on 404s (two conflicting tags).
    robots: {
      googleBot: {
        "max-video-preview": -1,
        "max-image-preview": "large",
        "max-snippet": -1,
      },
    },
  };
}

// Marketing pages render the seasonal banner (Navbar) from the date they were
// rendered on: re-render at most hourly so static pages never serve a stale
// season (the home and /christmas-delivery already do; dynamic pages unaffected).
export const revalidate = 3600;

export function generateStaticParams() {
  return routing.locales.map((locale) => ({ locale }));
}

export default async function LocaleLayout({ children, params }: Props) {
  const { locale } = await params;

  if (!hasLocale(routing.locales, locale)) {
    notFound();
  }

  // Static rendering: hand next-intl the locale from params so it never reads the
  // request headers (which would opt every route out of static/ISR). Every page
  // and nested layout that should be static calls it too (Next renders them apart).
  setRequestLocale(locale);

  // Client components get every namespace except the server-only long-form copy.
  const messages = clientMessages(await getMessages());

  return (
    <RootDocument lang={locale}>
      <NextIntlClientProvider messages={messages}>
        {children}
        <Tracking />
      </NextIntlClientProvider>
    </RootDocument>
  );
}
