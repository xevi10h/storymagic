#!/usr/bin/env node
/**
 * Downloads the print fonts from Google Fonts (OFL) and embeds them as base64
 * in src/lib/pdf/fonts/font-data.ts so PDF rendering never fetches fonts at
 * runtime (serverless functions do not ship /public, and gstatic can fail).
 *
 * Run: node scripts/build-pdf-fonts.mjs
 */

import { writeFileSync, mkdirSync } from "fs";
import { resolve, dirname } from "path";
import { fileURLToPath } from "url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const OUT = resolve(__dirname, "../src/lib/pdf/fonts/font-data.ts");

// Symbols subset (Noto Sans Symbols 2): hearts, stars, flowers, sun/cloud, check.
// Neither Fredoka nor Plus Jakarta Sans has these glyphs.
const SYMBOLS_TEXT = "♥♡★☆❤✿☀☁✓✶❀";

const FONTS = [
  { name: "FREDOKA_400", css: "family=Fredoka:wght@400", style: "normal", weight: "400" },
  { name: "FREDOKA_600", css: "family=Fredoka:wght@600", style: "normal", weight: "600" },
  { name: "JAKARTA_400", css: "family=Plus+Jakarta+Sans:wght@400", style: "normal", weight: "400" },
  { name: "JAKARTA_400_ITALIC", css: "family=Plus+Jakarta+Sans:ital,wght@1,400", style: "italic", weight: "400" },
  { name: "JAKARTA_600", css: "family=Plus+Jakarta+Sans:wght@600", style: "normal", weight: "600" },
  { name: "JAKARTA_700", css: "family=Plus+Jakarta+Sans:wght@700", style: "normal", weight: "700" },
  {
    name: "SYMBOLS_400",
    css: `family=Noto+Sans+Symbols+2&text=${encodeURIComponent(SYMBOLS_TEXT)}`,
    style: "normal",
    weight: "400",
  },
];

async function fetchTtfUrl(css) {
  // A non-browser user agent makes Google Fonts serve TTF instead of WOFF2.
  const res = await fetch(`https://fonts.googleapis.com/css2?${css}`, {
    headers: { "User-Agent": "curl/8" },
  });
  if (!res.ok) throw new Error(`CSS fetch failed ${res.status} for ${css}`);
  const text = await res.text();
  const match = text.match(/src:\s*url\(([^)]+)\)\s*format\('truetype'\)/);
  if (!match) throw new Error(`No TTF src in CSS for ${css}`);
  return match[1];
}

const lines = [
  "// AUTO-GENERATED by scripts/build-pdf-fonts.mjs — do not edit by hand.",
  "// Fonts: Fredoka, Plus Jakarta Sans, Noto Sans Symbols 2 (subset) — SIL Open Font License 1.1.",
  "",
];

for (const f of FONTS) {
  const url = await fetchTtfUrl(f.css);
  const res = await fetch(url);
  if (!res.ok) throw new Error(`Font fetch failed ${res.status}: ${url}`);
  const buf = Buffer.from(await res.arrayBuffer());
  console.log(`${f.name}: ${(buf.length / 1024).toFixed(0)} KB`);
  lines.push(`export const ${f.name} = "data:font/ttf;base64,${buf.toString("base64")}";`);
}

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, lines.join("\n") + "\n");
console.log(`Wrote ${OUT}`);
