#!/usr/bin/env node
/**
 * Downloads the print fonts from Google Fonts (OFL) and embeds them as base64
 * in src/lib/pdf/fonts/font-data.ts so PDF rendering never fetches fonts at
 * runtime (serverless functions do not ship /public, and gstatic can fail).
 *
 * Every text font is then patched with a U+202F NARROW NO-BREAK SPACE glyph
 * (scripts/patch-font-nnbsp.py, needs Python fontTools + brotli): Google's builds lack it and
 * French typography needs it before ? ! ; and inside « guillemets ». The same glyph (Jakarta's)
 * is written as public/fonts/print-spaces.woff2 for the web book viewer.
 *
 * Run: node scripts/build-pdf-fonts.mjs             (download + patch)
 *      node scripts/build-pdf-fonts.mjs --repatch   (patch the fonts already embedded —
 *                                                     no download, so glyphs never drift)
 */

import { writeFileSync, mkdirSync, readFileSync, mkdtempSync, rmSync } from "fs";
import { resolve, dirname, join } from "path";
import { tmpdir } from "os";
import { execFileSync } from "child_process";
import { fileURLToPath } from "url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const OUT = resolve(__dirname, "../src/lib/pdf/fonts/font-data.ts");

// Symbols subset (Noto Sans Symbols 2): hearts, stars, flowers, sun/cloud, check.
// Neither Fredoka nor Plus Jakarta Sans has these glyphs.
const SYMBOLS_TEXT = "♥♡★☆❤✿☀☁✓✶❀";

const FONTS = [
  { name: "FREDOKA_400", css: "family=Fredoka:wght@400", style: "normal", weight: "400" },
  { name: "FREDOKA_600", css: "family=Fredoka:wght@600", style: "normal", weight: "600" },
  { name: "JAKARTA_400", css: "family=Plus+Jakarta+Sans:wght@400", style: "normal", weight: "400" },
  { name: "JAKARTA_400_ITALIC", css: "family=Plus+Jakarta+Sans:ital,wght@1,400", style: "italic", weight: "400" },
  { name: "JAKARTA_600", css: "family=Plus+Jakarta+Sans:wght@600", style: "normal", weight: "600" },
  { name: "JAKARTA_700", css: "family=Plus+Jakarta+Sans:wght@700", style: "normal", weight: "700" },
  {
    name: "SYMBOLS_400",
    css: `family=Noto+Sans+Symbols+2&text=${encodeURIComponent(SYMBOLS_TEXT)}`,
    style: "normal",
    weight: "400",
  },
];

async function fetchTtfUrl(css) {
  // A non-browser user agent makes Google Fonts serve TTF instead of WOFF2.
  const res = await fetch(`https://fonts.googleapis.com/css2?${css}`, {
    headers: { "User-Agent": "curl/8" },
  });
  if (!res.ok) throw new Error(`CSS fetch failed ${res.status} for ${css}`);
  const text = await res.text();
  const match = text.match(/src:\s*url\(([^)]+)\)\s*format\('truetype'\)/);
  if (!match) throw new Error(`No TTF src in CSS for ${css}`);
  return match[1];
}

const PATCHER = resolve(__dirname, "patch-font-nnbsp.py");

/** Adds U+202F to a text font (the symbols subset only carries its own glyphs). */
function patchNnbsp(name, buf) {
  if (name.startsWith("SYMBOLS")) return buf;
  const dir = mkdtempSync(join(tmpdir(), "pdf-font-"));
  try {
    const src = join(dir, "in.ttf");
    const dst = join(dir, "out.ttf");
    writeFileSync(src, buf);
    const note = execFileSync("python3", [PATCHER, src, dst], { encoding: "utf8" }).trim();
    console.log(`  ${name}: ${note}`);
    return readFileSync(dst);
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}

const lines = [
  "// AUTO-GENERATED by scripts/build-pdf-fonts.mjs — do not edit by hand.",
  "// Fonts: Fredoka, Plus Jakarta Sans, Noto Sans Symbols 2 (subset) — SIL Open Font License 1.1.",
  "",
];

const existing = process.argv.includes("--repatch")
  ? new Map(
      [...readFileSync(OUT, "utf8").matchAll(/^export const (\w+) = "data:font\/ttf;base64,([^"]+)";$/gm)].map((m) => [m[1], Buffer.from(m[2], "base64")]),
    )
  : null;

for (const f of FONTS) {
  let buf;
  if (existing) {
    buf = existing.get(f.name);
    if (!buf) throw new Error(`--repatch: ${f.name} not found in ${OUT}`);
  } else {
    const url = await fetchTtfUrl(f.css);
    const res = await fetch(url);
    if (!res.ok) throw new Error(`Font fetch failed ${res.status}: ${url}`);
    buf = Buffer.from(await res.arrayBuffer());
  }
  buf = patchNnbsp(f.name, buf);
  console.log(`${f.name}: ${(buf.length / 1024).toFixed(0)} KB`);
  lines.push(`export const ${f.name} = "data:font/ttf;base64,${buf.toString("base64")}";`);
}

// Web viewer: the U+202F glyph of the patched Plus Jakarta Sans, alone (see globals.css)
{
  const dir = mkdtempSync(join(tmpdir(), "pdf-font-"));
  try {
    const m = lines.find((l) => l.startsWith("export const JAKARTA_400 ="));
    writeFileSync(join(dir, "jakarta.ttf"), Buffer.from(m.split("base64,")[1].slice(0, -2), "base64"));
    console.log(execFileSync("python3", [PATCHER, "--web", join(dir, "jakarta.ttf"), resolve(__dirname, "../public/fonts/print-spaces.woff2")], { encoding: "utf8" }).trim());
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, lines.join("\n") + "\n");
console.log(`Wrote ${OUT}`);
